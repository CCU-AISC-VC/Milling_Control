"""Self-generated sample G-code programs (the lab has no CAM output yet; user decision 2026-10-22).

Program frame: origin at the stock's top corner, X/Y along the stock edges, Z up, Z = 0 at
the top face (so cutting happens at Z < 0). Stock 200 x 200 x 50 mm (cell config).
"""
from __future__ import annotations

import math


def _f(v: float) -> str:
    return f"{v:.3f}".rstrip("0").rstrip(".") if abs(v) >= 1e-9 else "0"


def make_sample_pocket_contour(
    feed_cut: float = 800.0,
    feed_plunge: float = 300.0,
    safe_z: float = 10.0,
    rpm: float = 8000.0,
) -> str:
    """Contour with corner arcs (R format) + circular pocket (helical entry, I/J circles) + S-slot."""
    L: list[str] = []
    a = L.append
    a("( sample_pocket_contour: generated by milling_sim.sample_gcode )")
    a("( stock 200x200x50 mm, origin at top corner, Z0 = top face )")
    a("G21 G90 G17 G54")
    a(f"S{_f(rpm)} M3")
    a(f"G0 Z{_f(safe_z)}")

    # --- Op 1: rectangular contour 20..180 with R10 corner arcs, two depths (CW = climb for outside)
    a("( op1: contour, R10 corners )")
    x0, y0, x1, y1, r = 20.0, 20.0, 180.0, 180.0, 10.0
    a(f"G0 X{_f(x0 + r)} Y{_f(y0)}")
    for z in (-2.0, -4.0):
        a(f"G1 Z{_f(z)} F{_f(feed_plunge)}")
        a(f"G1 X{_f(x1 - r)} Y{_f(y0)} F{_f(feed_cut)}")
        a(f"G3 X{_f(x1)} Y{_f(y0 + r)} R{_f(r)}")
        a(f"G1 X{_f(x1)} Y{_f(y1 - r)}")
        a(f"G3 X{_f(x1 - r)} Y{_f(y1)} R{_f(r)}")
        a(f"G1 X{_f(x0 + r)} Y{_f(y1)}")
        a(f"G3 X{_f(x0)} Y{_f(y1 - r)} R{_f(r)}")
        a(f"G1 X{_f(x0)} Y{_f(y0 + r)}")
        a(f"G3 X{_f(x0 + r)} Y{_f(y0)} R{_f(r)}")
    a(f"G0 Z{_f(safe_z)}")

    # --- Op 2: circular pocket centre (100,100) radius 35: helical entry on r=10, then rings
    a("( op2: circular pocket, helical entry + concentric rings )")
    cx, cy = 100.0, 100.0
    a(f"G0 X{_f(cx + 10)} Y{_f(cy)}")
    a("G1 Z0 F" + _f(feed_plunge))
    for z_top, z in ((0.0, -3.0), (-3.0, -6.0)):
        # helix: one full CCW circle while descending 3 mm (I/J incremental from start)
        a(f"G3 X{_f(cx + 10)} Y{_f(cy)} Z{_f(z)} I-10 J0 F{_f(feed_plunge)}")
        a(f"G3 X{_f(cx + 10)} Y{_f(cy)} I-10 J0 F{_f(feed_cut)}")  # clean full circle at depth
        for rr in (20.0, 30.0, 35.0):
            a(f"G1 X{_f(cx + rr)} Y{_f(cy)}")
            a(f"G3 X{_f(cx + rr)} Y{_f(cy)} I{_f(-rr)} J0")
        a(f"G1 X{_f(cx + 10)} Y{_f(cy)}")
    a(f"G0 Z{_f(safe_z)}")

    # --- Op 3: S-shaped slot with G2/G3 (I/J) at Z -2
    a("( op3: S slot )")
    a("G0 X40 Y160")
    a(f"G1 Z-2 F{_f(feed_plunge)}")
    a(f"G1 X60 Y160 F{_f(feed_cut)}")
    a("G2 X80 Y140 I0 J-20")
    a("G3 X100 Y120 I20 J0")
    a("G1 X120 Y120")
    a(f"G0 Z{_f(safe_z)}")
    a("M5")
    a("G0 X0 Y0")
    a("M30")
    return "\n".join(L) + "\n"


def make_sample_face_boss(
    feed_cut: float = 1000.0,
    feed_plunge: float = 300.0,
    safe_z: float = 10.0,
    rpm: float = 10000.0,
    stepover: float = 8.0,
) -> str:
    """Zig-zag face pass (Z -1) + circular boss contour (two depths, G2) + two straight slots."""
    L: list[str] = []
    a = L.append
    a("( sample_face_boss: generated by milling_sim.sample_gcode )")
    a("( 200x200 program area, Z0 = top face; used by the second robot in the dual cell )")
    a("G21 G90 G17 G54")
    a(f"S{_f(rpm)} M3")
    a(f"G0 Z{_f(safe_z)}")
    # --- op 1: zig-zag face milling over 15..185 x 15..185 at Z -1
    a("( op1: zig-zag face pass )")
    x0, x1, y0, y1 = 15.0, 185.0, 15.0, 185.0
    a(f"G0 X{_f(x0)} Y{_f(y0)}")
    a(f"G1 Z-1 F{_f(feed_plunge)}")
    y = y0
    forward = True
    first = True
    while y <= y1 + 1e-9:
        xe = x1 if forward else x0
        a(f"G1 X{_f(xe)} Y{_f(y)}" + (f" F{_f(feed_cut)}" if first else ""))
        first = False
        y_next = y + stepover
        if y_next <= y1 + 1e-9:
            a(f"G1 X{_f(xe)} Y{_f(y_next)}")
        y = y_next
        forward = not forward
    a(f"G0 Z{_f(safe_z)}")
    # --- op 2: circular boss r = 45 around (100, 100), contour at Z -3 and Z -5 (CW = G2)
    a("( op2: circular boss contour )")
    cx, cy, r = 100.0, 100.0, 45.0
    a(f"G0 X{_f(cx + r)} Y{_f(cy)}")
    for z in (-3.0, -5.0):
        a(f"G1 Z{_f(z)} F{_f(feed_plunge)}")
        a(f"G2 X{_f(cx + r)} Y{_f(cy)} I{_f(-r)} J0 F{_f(feed_cut)}")
    a(f"G0 Z{_f(safe_z)}")
    # --- op 3: two slots at Z -2
    a("( op3: slots )")
    for yy in (40.0, 160.0):
        a(f"G0 X30 Y{_f(yy)}")
        a(f"G1 Z-2 F{_f(feed_plunge)}")
        a(f"G1 X170 Y{_f(yy)} F{_f(feed_cut)}")
        a(f"G0 Z{_f(safe_z)}")
    a("M5")
    a("G0 X0 Y0")
    a("M30")
    return "\n".join(L) + "\n"


def make_sample_5axis_wave(
    feed_cut: float = 1500.0,
    feed_plunge: float = 400.0,
    safe_z: float = 15.0,
    rpm: float = 12000.0,
    ball_radius: float = 4.0,
    stepover: float = 4.0,
    step_x: float = 2.0,
    amplitude: float = 3.0,
    wavelength: float = 90.0,
    lead_deg: float = 10.0,
) -> str:
    """5-axis finishing of a sine-wave surface with a ball mill: tool axis = surface normal tilted
    by a lead angle toward the feed direction; every G1 carries the tool vector I J K
    (tip -> spindle). Surface: z = -A (1 - cos(2 pi (x - x0) / lambda)), x in [10, 190], y in [10, 190].
    """
    L: list[str] = []
    a = L.append
    a("( sample_5axis_wave: generated by milling_sim.sample_gcode )")
    a("( ball mill, tool vector I J K on G1 = tool axis unit vector tip->spindle; 200x200 area, Z0 = top face )")
    a("G21 G90 G17 G54")
    a(f"S{_f(rpm)} M3")
    x0, x1, y0, y1 = 10.0, 190.0, 10.0, 190.0
    r = ball_radius

    def surf(x):
        ph = 2 * math.pi * (x - x0) / wavelength
        z = -amplitude * (1 - math.cos(ph))
        dz = -amplitude * (2 * math.pi / wavelength) * math.sin(ph)
        return z, dz

    def line(x, y, forward):
        z, dz = surf(x)
        nx, nz = -dz, 1.0
        nn = math.hypot(nx, nz)
        nx, nz = nx / nn, nz / nn
        # lead: rotate the normal about +Y toward the feed direction (+x when forward)
        lead = math.radians(lead_deg) * (1.0 if forward else -1.0)
        ax = nx * math.cos(lead) + nz * math.sin(lead)
        az = -nx * math.sin(lead) + nz * math.cos(lead)
        # ball centre sits on the surface normal; the programmed tip is centre - r * axis
        cx, cz = x + r * nx, z + r * nz
        tx, tz = cx - r * ax, cz - r * az
        return f"G1 X{_f(tx)} Y{_f(y)} Z{_f(tz)} I{_f(ax)} J0 K{_f(az)}"

    a(f"G0 Z{_f(safe_z)} I0 J0 K1")
    a(f"G0 X{_f(x0)} Y{_f(y0)}")
    y = y0
    forward = True
    first = True
    while y <= y1 + 1e-9:
        xs = [x0 + k * step_x for k in range(int(round((x1 - x0) / step_x)) + 1)]
        if not forward:
            xs = xs[::-1]
        if first:
            z, _ = surf(xs[0])
            a(f"G1 Z{_f(z + 2.0)} F{_f(feed_plunge)}")
            a(line(xs[0], y, forward) + f" F{_f(feed_plunge)}")
            a(f"F{_f(feed_cut)}")
            first = False
        for x in xs:
            a(line(x, y, forward))
        y_next = y + stepover
        if y_next <= y1 + 1e-9:
            # step over while re-orienting to the next pass's lead angle, at the slow feed
            nxt = line(xs[-1], y_next, not forward).replace("G1 ", "G1 ")
            a(nxt + f" F{_f(feed_plunge)}")
            a(f"F{_f(feed_cut)}")
        y = y_next
        forward = not forward
    a(f"G0 Z{_f(safe_z)} I0 J0 K1")
    a("M5")
    a("G0 X0 Y0")
    a("M30")
    return "\n".join(L) + "\n"


def make_unit_square(side_mm: float = 100.0, feed: float = 600.0) -> str:
    s = _f(side_mm)
    return "\n".join(
        [
            "G21 G90 G17",
            f"G1 X{s} Y0 F{_f(feed)}",
            f"G1 X{s} Y{s}",
            f"G1 X0 Y{s}",
            "G1 X0 Y0",
            "M30",
        ]
    ) + "\n"


def full_circle_length_mm(r_mm: float) -> float:
    return 2 * math.pi * r_mm
